"""Continuation import outline bootstrap.

The continuation import baseline is intentionally small: it writes
the imported chapters, characters, world blueprint, and a single
``pipeline_stage="outline_bootstrapping"`` marker. Everything else
(overall, arcs, future chapters, rolling detail) is generated by
:class:`ContinuationOutlineBootstrapper` *after* the baseline exists
so the workbench never shows a fabricated future plot.

This module owns the contracts that drive that flow:

* :class:`BootstrapPhaseId` / :data:`BOOTSTRAP_PHASES` — the order
  the bootstrapper walks through.
* :class:`BootstrapReadiness` — a pure pydantic snapshot returned by
  :func:`validate_continuation_bootstrap`. The validator is the
  *only* allowed way for callers to decide whether the next chapter
  is write-ready; it must work on disk, not on transient route
  memory, so a page reload always agrees.
* :func:`validate_continuation_bootstrap` — the pure readiness
  validator. It checks concrete files (``outline.json``,
  ``state.json``, ``rolling_outline.json``) and concrete content
  (an arc covering the next chapter, rolling detail for the next
  chapter, a protagonist card, world premise + rules or power
  system, current chapter equals imported chapters). It never
  inspects ``pipeline_stage`` so the validator survives a partial
  bootstrap run.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field


BootstrapPhaseId = Literal[
    "source_analysis",
    "outline_foundation",
    "character_roster",
    "world_context",
    "chapter_window",
    "readiness_check",
]


BOOTSTRAP_PHASES: tuple[BootstrapPhaseId, ...] = (
    "source_analysis",
    "outline_foundation",
    "character_roster",
    "world_context",
    "chapter_window",
    "readiness_check",
)


class BootstrapReadiness(BaseModel):
    """A pure snapshot of whether the next chapter is write-ready.

    ``ready`` is the only field a caller should branch on. The
    ``errors`` list is a human-readable list of failing field
    codes; the bootstrapper uses the same codes to surface the
    UI banner. ``next_chapter`` is always the current chapter
    plus one — even when the project is not yet ready — so the
    wizard can render the next-chapter banner before the
    bootstrap completes.
    """

    model_config = ConfigDict(extra="forbid", strict=True)

    ready: bool
    next_chapter: int = Field(ge=1)
    errors: list[str] = Field(default_factory=list)


def _read_json(path: Path) -> Any:
    if not path.is_file():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def _coerce_chapter_numbers(value: Any) -> list[int]:
    """Return ``value`` as a list of positive ints.

    Robust against ``None`` / non-list / non-int entries so the
    validator never raises while scanning partially-written project
    files.
    """

    if not isinstance(value, list):
        return []
    numbers: list[int] = []
    for item in value:
        if isinstance(item, bool):
            continue
        if isinstance(item, int) and item > 0:
            numbers.append(item)
    return numbers


def _has_protagonist_card(characters: Any) -> bool:
    if not isinstance(characters, list):
        return False
    for card in characters:
        if not isinstance(card, dict):
            continue
        role = str(card.get("character_tier") or card.get("role") or "").strip().lower()
        if role in {"protagonist", "主角"}:
            return True
    return False


def _world_premise_and_rules(blueprint: Any, state: Any) -> tuple[str, bool, bool]:
    """Return ``(premise, has_rules, has_power_system)``.

    A project passes when ``premise`` is non-empty *and* at least
    one of ``world_rules`` / ``power_system`` is non-empty. The
    ``premise`` is read from the blueprint (the long-lived
    source of truth), with the state's outline as a fallback so a
    project whose blueprint was wiped still surfaces a usable
    premise.
    """

    premise = ""
    has_rules = False
    has_power_system = False
    if isinstance(blueprint, dict):
        premise = str(blueprint.get("premise") or "").strip()
        rules = blueprint.get("world_rules")
        if isinstance(rules, list) and any(str(item or "").strip() for item in rules):
            has_rules = True
        power = blueprint.get("power_system")
        if isinstance(power, list) and any(str(item or "").strip() for item in power):
            has_power_system = True
    if not premise and isinstance(state, dict):
        premise = str(state.get("outline") or state.get("world_summary") or "").strip()
    return premise, has_rules, has_power_system


def _arc_covers(arc: dict[str, Any], chapter_number: int) -> bool:
    if not isinstance(arc, dict):
        return False
    start = arc.get("start_chapter")
    end = arc.get("end_chapter")
    if not isinstance(start, int) or isinstance(start, bool):
        return False
    if not isinstance(end, int) or isinstance(end, bool):
        return False
    return start <= chapter_number <= end


def validate_continuation_bootstrap(project_root: str | Path) -> BootstrapReadiness:
    """Return a pure readiness snapshot for ``project_root``.

    The function never raises; it returns a populated
    :class:`BootstrapReadiness` whose ``errors`` list describes
    what is missing. The check is intentionally file-driven so a
    route reload (or a backfill script) and a re-validated
    in-memory store always agree.

    The error codes form a stable contract; the bootstrap UI keys
    its banners off them.

    * ``import_overall_required`` — ``outline.overall.story`` is blank
    * ``import_arc_required`` — no arc covers the current chapter
    * ``import_future_arc_required`` — no arc covers the next chapter
    * ``import_character_card_required`` — no protagonist card on disk
    * ``import_world_context_required`` — premise / rules / power
      system are all blank
    * ``import_chapter_window_required:{n}`` — no rolling detail for
      chapter ``n`` (next chapter)
    * ``import_current_chapter_mismatch`` — ``state.current_chapter``
      does not equal the maximum committed chapter number
    """

    root = Path(project_root)
    errors: list[str] = []
    next_chapter = 1

    project = _read_json(root / ".webnovel" / "project.json")
    state = _read_json(root / ".webnovel" / "state.json")
    outline = _read_json(root / ".webnovel" / "outline.json")

    current_chapter = 0
    if isinstance(state, dict):
        try:
            current_chapter = int(state.get("current_chapter") or 0)
        except (TypeError, ValueError):
            current_chapter = 0
    if current_chapter <= 0 and isinstance(project, dict):
        try:
            current_chapter = int(project.get("current_chapter") or 0)
        except (TypeError, ValueError):
            current_chapter = 0
    next_chapter = max(1, current_chapter + 1)

    # Overall core fields: the plan rule requires evidence-backed
    # overall. An empty story string is the cheapest signal.
    overall = outline.get("overall") if isinstance(outline, dict) else None
    if not isinstance(overall, dict) or not str(overall.get("story") or "").strip():
        errors.append("import_overall_required")

    # Arc coverage: at least one historical arc must cover the
    # current chapter, and at least one future arc must cover the
    # next chapter.
    arcs = outline.get("arcs") if isinstance(outline, dict) else []
    if not isinstance(arcs, list) or not arcs:
        errors.append("import_arc_required")
        errors.append("import_future_arc_required")
    else:
        if not any(_arc_covers(arc, current_chapter) for arc in arcs):
            errors.append("import_arc_required")
        if not any(_arc_covers(arc, next_chapter) for arc in arcs):
            errors.append("import_future_arc_required")

    # Protagonist card: search both the project's character_profiles
    # and the state's characters list so the test does not depend
    # on which file the import put it in.
    characters: list[Any] = []
    if isinstance(project, dict):
        characters.extend(project.get("character_profiles") or [])
    if isinstance(state, dict):
        characters.extend(state.get("characters") or [])
    if not _has_protagonist_card(characters):
        errors.append("import_character_card_required")

    blueprint = project.get("world_blueprint") if isinstance(project, dict) else None
    premise, has_rules, has_power_system = _world_premise_and_rules(blueprint, state)
    if not premise or not (has_rules or has_power_system):
        errors.append("import_world_context_required")

    # Rolling detail: the next chapter must have a row in
    # ``.story-system/outline-generation/rolling_outline.json``.
    rolling = _read_json(
        root / ".story-system" / "outline-generation" / "rolling_outline.json"
    )
    rolling_chapters = (
        rolling.get("chapters") if isinstance(rolling, dict) else None
    )
    rolling_numbers: set[int] = set()
    if isinstance(rolling_chapters, list):
        rolling_numbers = set(_coerce_chapter_numbers(
            [
                item.get("chapter_number") if isinstance(item, dict) else None
                for item in rolling_chapters
            ]
        ))
    if next_chapter not in rolling_numbers:
        errors.append(f"import_chapter_window_required:{next_chapter}")

    # Current chapter must equal the maximum committed chapter.
    chapters_dir = root / ".story-system" / "chapters"
    committed: list[int] = []
    if chapters_dir.is_dir():
        for chapter_file in chapters_dir.glob("*.json"):
            try:
                payload = json.loads(chapter_file.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError):
                continue
            if isinstance(payload, dict):
                try:
                    number = int(payload.get("chapter_number") or 0)
                except (TypeError, ValueError):
                    number = 0
                if number > 0:
                    committed.append(number)
    if not committed or max(committed) != current_chapter:
        errors.append("import_current_chapter_mismatch")

    return BootstrapReadiness(
        ready=not errors,
        next_chapter=next_chapter,
        errors=errors,
    )


__all__ = [
    "BOOTSTRAP_PHASES",
    "BootstrapPhaseId",
    "BootstrapReadiness",
    "validate_continuation_bootstrap",
]
